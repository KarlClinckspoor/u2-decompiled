#!/usr/bin/env python3
"""Generate c/test/gen/gen_data.h for the test harness.

The harness runs the C of c/ with stand-ins for the machine. The game's variables live in one data
segment in the assembly (src/U2DATA.ASM) but are separate C variables here, so the harness needs

  - the initial image of the data segment, built from U2DATA.ASM (db/dw lines, in order);
  - a definition of every variable that c/u2.h declares `extern` and that is a data-segment
    symbol (a non-pointer one), named and typed exactly as u2.h says;
  - a table {address of the C variable, its size, its offset in the data segment}, which the harness
    uses to give the variables their initial values and to move the PLAYER record (D:0036-0135) and
    the monster table (D:0137-0236) between the files and the variables.

Run from anywhere: python3 c/test/gendata.py   (writes c/test/gen/gen_data.h)
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import syms as S

POINTERS = {'MapCellPtr', 'DungeonCellPtr', 'MapBufPtr', 'MonsterBufPtr', 'TalkBufPtr', 'TilePtrTbl'}
SPECIAL = {'PlayerRecord'}          # the record itself is handled by the harness
ALIAS = {'Attributes': 'Strength'}


def number(tok, table):
    tok = tok.strip()
    m = re.match(r'^D_END\s*\+\s*([0-9A-Fa-f]+)h$', tok, re.I)
    if m:
        return table['D_END'].addr + int(m.group(1), 16)
    if re.match(r'^[0-9][0-9A-Fa-f]*h$', tok, re.I):
        return int(tok[:-1], 16)
    if re.match(r'^[0-9]+$', tok):
        return int(tok)
    sym = table.get(tok.upper())
    if sym is not None and sym.addr is not None:
        return sym.addr
    raise ValueError('cannot evaluate %r' % tok)


def build_image(table):
    img = bytearray()
    started = False
    for l in S.read('U2DATA.ASM'):
        code = l.split(';')[0]
        if re.match(r'^D_START\b', code):
            started = True
        if not started:
            continue
        m = re.match(r'\s*(db|dw)\s+(.*)', code, re.I)
        if not m:
            continue
        width = 1 if m.group(1).lower() == 'db' else 2
        for item in m.group(2).split(','):
            d = re.match(r'\s*(\d+)\s+dup\s*\(\s*(.*?)\s*\)\s*$', item, re.I)
            if d:
                n, v = int(d.group(1)), (0 if d.group(2) == '?' else number(d.group(2), table))
            else:
                n, v = 1, number(item, table)
            for _ in range(n):
                img += (v & ((1 << (8 * width)) - 1)).to_bytes(width, 'little')
    return bytes(img)


def externs():
    """(type, declarator, name, is_const) for each `extern` data declaration of c/u2.h."""
    out = []
    text = re.sub(r'/\*.*?\*/', '', open(os.path.join(ROOT, 'c', 'u2.h')).read(), flags=re.S)
    for l in text.splitlines():
        l = l.strip()
        m = re.match(r'^extern\s+(const\s+)?(u8|u16|u32|char)\s+(.*);$', l)
        if not m:
            continue
        for decl in m.group(3).split(','):
            decl = decl.strip()
            n = re.match(r'^(\*?)\s*([A-Za-z_]\w*)', decl)
            out.append((m.group(2), decl, n.group(2), bool(m.group(1)), bool(n.group(1))))
    return out


def main():
    table = S.table()
    image = build_image(table)
    d_end = table['D_END'].addr
    if len(image) != d_end:
        sys.exit('image is %d bytes but D_END is %d' % (len(image), d_end))
    defs, ents, consts = [], [], []
    seen = set()
    for typ, decl, name, is_const, is_ptr in externs():
        sym = table.get(ALIAS.get(name, name).upper())      # the C array Attributes is the asm's Strength...Intelligence
        if sym is None or sym.seg != 'D' or sym.addr is None or name in seen:
            continue
        seen.add(name)
        if is_ptr or name in POINTERS or name in SPECIAL:
            continue
        if is_const:
            n = re.search(r'\[(\d+)\]', decl)
            count = int(n.group(1))
            vals = [image[sym.addr + 2 * i] | image[sym.addr + 2 * i + 1] << 8 for i in range(count)]
            consts.append('const %s %s = { %s };' % (typ, decl, ', '.join('0x%04X' % v for v in vals)))
            continue
        defs.append('%s %s;' % (typ, decl))
        ents.append('    { (void *)&%s, sizeof(%s), 0x%04X, "%s" },' % (name, name, sym.addr, name))
    out = []
    out.append('/* generated by c/test/gendata.py from src/U2DATA.ASM and c/u2.h: do not edit */')
    out.append('#define D_END 0x%04X' % d_end)
    for n in ('MapBufPtr', 'MonsterBufPtr', 'TalkBufPtr', 'TilePtrTbl', 'PlayerRecord', 'MonsterX'):
        out.append('#define A_%s 0x%04X' % (n, table[n.upper()].addr))
    out.append('static const unsigned char DataImage[D_END] = {')
    for i in range(0, len(image), 16):
        out.append('    ' + ','.join('0x%02X' % b for b in image[i:i + 16]) + ',')
    out.append('};')
    out += defs + consts
    out.append('struct VarEnt { void *p; unsigned size; unsigned addr; const char *name; };')
    out.append('static const struct VarEnt Vars[] = {')
    out += ents
    out.append('    { 0, 0, 0, 0 }')
    out.append('};')
    os.makedirs(os.path.join(HERE, 'gen'), exist_ok=True)
    with open(os.path.join(HERE, 'gen', 'gen_data.h'), 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('gen_data.h: %d variables, image %d bytes' % (len(ents), len(image)))


if __name__ == '__main__':
    main()
